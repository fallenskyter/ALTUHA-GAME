"""Character B (barefoot): cut foot sprites + 12 portraits out of the second sheet and
   write swizzled textures + metadata header (poses_b.h)."""
import numpy as np, math, sys
from PIL import Image
from scipy import ndimage as ndi
sys.path.insert(0,'/tmp/v6/tools')
from sheetlib import matte
SHEET='/mnt/user-data/uploads/1795456597606_image.png'
OUT='/tmp/v6'
K=480/1280.0; SX1=6.28*1.36; SY1=6.28
S=2.825531914893617           # same px-per-unit as character A, so both feet are the same size on screen
CROP_H=310                    # rows kept above the sole (same as A's cells)
sheet=np.array(Image.open(SHEET).convert('RGB'))
H,W=sheet.shape[:2]
minc=sheet.min(axis=2)
raw_fg=minc<236
lab,n=ndi.label(raw_fg,structure=np.ones((3,3)))

def swizzle(arr,bpp):
    h,w=arr.shape[0],arr.shape[1]; rowbytes=w*bpp
    return arr.reshape(h,rowbytes).reshape(h//8,8,rowbytes//16,16).transpose(0,2,1,3).copy().tobytes()

def isolate(seed):
    l=lab[seed[1],seed[0]]
    if l==0: raise SystemExit('seed not on sprite: %s'%(seed,))
    m=lab==l
    ys,xs=np.where(m)
    x0,x1,y0,y1=xs.min(),xs.max()+1,ys.min(),ys.max()+1
    pad=8
    X0,X1,Y0,Y1=max(0,x0-pad),min(W,x1+pad),y0,min(H,y1+pad)
    crop=sheet[Y0:Y1,X0:X1].copy()
    keep=ndi.binary_dilation(m[Y0:Y1,X0:X1],iterations=2)
    crop[~keep]=255
    return crop
# (name, seed on the leg, pose slots that use it)
SPRITES={'a':((105,560)),'b':((285,560)),'c':((470,560)),'d':((700,560))}
POSE_USE={0:'b',3:'c',4:'a',5:'c',6:'b',7:'d',8:'a'}
cache={}
def process(key):
    if key in cache: return cache[key]
    crop=isolate(SPRITES[key])
    rgba=matte(np.dstack([crop,np.full(crop.shape[:2],255,np.uint8)]),False)
    al=rgba[:,:,3]>128
    ys,xs=np.where(al)
    maxY=ys.max(); minX,maxX=xs.min(),xs.max()
    h0=min(rgba.shape[0],maxY+1+round(2))
    top=max(0,h0-CROP_H)
    rgba=rgba[top:h0]; al=rgba[:,:,3]>128
    ys,xs=np.where(al)
    minX,maxX,minY,maxY=xs.min(),xs.max(),ys.min(),ys.max()
    h,w=rgba.shape[:2]
    # foot region = lowest 90 px of the sprite -> sole extents
    foot=al[max(0,maxY-90):maxY+1]
    fx=np.where(foot.any(axis=0))[0]
    soleMin=fx.min()/S; soleMax=(fx.max()+1)/S
    botY=(maxY+1)/S
    anchor=(soleMin+soleMax)/2
    soleYs=[]
    for t in range(24):
        xc=round((soleMin+(soleMax-soleMin)*t/23)*S); xc=min(w-1,max(0,xc))
        yb=-1
        for y in range(h-1,-1,-1):
            if al[y,max(0,xc-1):min(w-1,xc+1)+1].any(): yb=y;break
        soleYs.append(round(((yb+1 if yb>=0 else maxY+1)/S)-botY,2))
    def centerAt(r):
        y=min(h-1,round(r*S)); xs_=np.where(al[y])[0]
        return None if len(xs_)==0 else (xs_[0]+xs_[-1]+1)/2/S
    c1,c2=centerAt(4),centerAt(30)
    slope=((c2-c1)/26) if (c1 is not None and c2 is not None) else 0
    wu=w/S; hu=h/S
    wpx=max(2,round(wu*SX1*K)); hpx=min(256,max(2,round(hu*SY1*K)))
    arr=rgba.astype(np.float32); a=arr[:,:,3:4]/255.0
    pm=np.dstack([arr[:,:,:3]*a,arr[:,:,3:4]]).astype(np.uint8)
    im=Image.fromarray(pm,'RGBA').resize((wpx,hpx),Image.LANCZOS)
    q=np.array(im).astype(np.float32); qa=q[:,:,3:4]/255.0
    rgb=np.where(qa>0.003,q[:,:,:3]/np.maximum(qa,0.003),0)
    fin=np.dstack([np.clip(rgb,0,255),q[:,:,3:4]]).astype(np.uint8)
    tex=np.zeros((256,256,4),np.uint8); tex[:hpx,:wpx]=fin
    info=dict(wu=wu,hu=hu,botY=botY,anchor=anchor,soleMin=soleMin,soleMax=soleMax,slope=slope,wpx=wpx,hpx=hpx,tw=256,th=256,soleYs=soleYs,tex=tex)
    cache[key]=info
    print(key,'units %.1f x %.1f'%(wu,hu),'px',wpx,hpx,'sole %.1f..%.1f'%(soleMin,soleMax),'anchor %.1f'%anchor,'botY %.1f'%botY,'slope %.3f'%slope)
    return info
poses=[None]*11
for idx in range(11):
    key=POSE_USE.get(idx,'b')
    info=process(key); poses[idx]=info
    if idx in POSE_USE:
        open(f'{OUT}/assets/bare_{idx:02d}.rgba','wb').write(swizzle(info['tex'],4))
with open(f'{OUT}/poses_b.h','w') as f:
    f.write('/* generated by tools/gen_char_b.py */\n#pragma once\nstatic const PoseInfo POSES_B[NPOSE] = {\n')
    for p in poses:
        f.write('  {%.3ff,%.3ff,%.3ff,%.3ff,%.3ff,%.3ff,%.4ff,%d,%d,%d,%d,{%s}},\n'%(p['wu'],p['hu'],p['botY'],p['anchor'],p['soleMin'],p['soleMax'],p['slope'],p['wpx'],p['hpx'],p['tw'],p['th'],','.join('%.2ff'%v for v in p['soleYs'])))
    f.write('};\n')
# ---- portraits: 12 frames, left column idle / right column happy ----
BOXES=[]
for (y0,y1) in [(13,211),(221,414),(422,616),(629,822),(834,1026),(1050,1241)]:
    BOXES.append((925,y0,1083,y1)); BOXES.append((1090,y0,1244,y1))
pw_list=[]
for i,(x0,y0,x1,y1) in enumerate(BOXES):
    pad=3
    cr=sheet[max(0,y0-pad):y1+pad,max(0,x0-pad):x1+pad]
    rgba=matte(np.dstack([cr,np.full(cr.shape[:2],255,np.uint8)]),True)
    h_,w_=rgba.shape[:2]; th=64; tw=min(64,round(w_*th/h_))
    arr=rgba.astype(np.float32); a=arr[:,:,3:4]/255.0
    pm=np.dstack([arr[:,:,:3]*a,arr[:,:,3:4]]).astype(np.uint8)
    q=np.array(Image.fromarray(pm,'RGBA').resize((tw,th),Image.LANCZOS)).astype(np.float32); qa=q[:,:,3:4]/255.0
    rgb=np.where(qa>0.003,q[:,:,:3]/np.maximum(qa,0.003),0)
    fin=np.dstack([np.clip(rgb,0,255),q[:,:,3:4]]).astype(np.uint8)
    tex=np.zeros((64,64,4),np.uint8); tex[:th,:tw]=fin
    open(f'{OUT}/assets/bport_{i:02d}.rgba','wb').write(swizzle(tex,4)); pw_list.append(tw)
print('portrait content widths',pw_list)
import json; json.dump(pw_list,open(f'{OUT}/tools/portw_b.json','w'))
