"""Write chars.h: per-character portrait widths and idle/happy frame lists."""
import json
b=json.load(open('/tmp/v6/tools/portw_b.json')); c=json.load(open('/tmp/v6/tools/portw_c.json'))
a=[62]*14
def row(v,n=14): return '{'+','.join(str(x) for x in (v+[v[-1]]*(n-len(v))))+'}'
idle=[[0,2,4,6,8,10,12],[0,2,4,6,8,10],[0,2,4,7,10,11]]
hap=[[1,3,5,7,9,11,13],[1,3,5,7,9,11],[3,6,9,1]]
def r8(v): return '{'+','.join(str(x) for x in (v+[v[0]]*(8-len(v))))+'}'
with open('/tmp/v6/chars.h','w') as f:
    f.write('/* generated by tools/gen_chars_h.py */\n#pragma once\n#define NCHAR 3\n')
    f.write('static const int PORT_COUNT[NCHAR] = {14, 12, 12};\n')
    f.write('static const int PORT_WF[NCHAR][14] = {%s, %s, %s};\n'%(row(a),row(b),row(c)))
    f.write('static const int PORT_NIDLE[NCHAR] = {%s};\nstatic const int PORT_NHAP[NCHAR] = {%s};\n'%(','.join(str(len(x)) for x in idle),','.join(str(len(x)) for x in hap)))
    f.write('static const int PORT_IDLE[NCHAR][8] = {%s};\nstatic const int PORT_HAP[NCHAR][8] = {%s};\n'%(','.join(r8(x) for x in idle),','.join(r8(x) for x in hap)))
print('chars.h ok')
