"""Character C (striped sweater): feet from the close-up row + 12 portraits (components auto-detected)."""
import numpy as np, json, sys
from PIL import Image
from scipy import ndimage as ndi
sys.path.insert(0,'/tmp/v6/tools')
from sheetlib import matte
SHEET='/mnt/user-data/uploads/1795606815120_image.png'     # the larger (1280x1169) copy of the sheet
OUT='/tmp/v6'
K=480/1280.0; SX1=6.28*1.36; SY1=6.28
Z=2.2                                    # PSP pixels per sheet pixel (natural aspect, pixel-art look)
SXu=SX1*K/Z; SYu=SY1*K/Z                 # sheet px per sprite unit (x / y)
MAXH=int(256/Z)                          # texture height limit -> rows kept above the sole
sheet=np.array(Image.open(SHEET).convert('RGB')); H,W=sheet.shape[:2]
fg=sheet.min(axis=2)<236
lab,n=ndi.label(fg,structure=np.ones((3,3)))
objs=ndi.find_objects(lab)
comps=[]
for i,sl in enumerate(objs,1):
    ys,xs=sl; area=int((lab[sl]==i).sum())
    comps.append(dict(id=i,y0=ys.start,y1=ys.stop,x0=xs.start,x1=xs.stop,area=area))
feet=sorted([c for c in comps if c['area']>600 and c['y0']>1000 and c['x1']<800],key=lambda c:c['x0'])
ports=[c for c in comps if c['area']>3000 and c['x0']>690 and c['y0']>190 and (c['x1']-c['x0'])>150 and (c['y1']-c['y0'])>180]
ports.sort(key=lambda c:(c['y0']//150,c['x0']))
print('foot pieces',len(feet),'portraits',len(ports))
assert len(feet)==7 and len(ports)==12

def swizzle(arr,bpp):
    h,w=arr.shape[0],arr.shape[1]; rowbytes=w*bpp
    return arr.reshape(h,rowbytes).reshape(h//8,8,rowbytes//16,16).transpose(0,2,1,3).copy().tobytes()
def isolate(c,pad=6):
    m=lab==c['id']
    X0,X1,Y0,Y1=max(0,c['x0']-pad),min(W,c['x1']+pad),max(0,c['y0']-2),min(H,c['y1']+pad)
    crop=sheet[Y0:Y1,X0:X1].copy()
    keep=ndi.binary_dilation(m[Y0:Y1,X0:X1],iterations=2); crop[~keep]=255
    return crop
def to_rgba(crop): return np.dstack([crop,np.full(crop.shape[:2],255,np.uint8)])
def premul_resize(rgba,wpx,hpx):
    arr=rgba.astype(np.float32); a=arr[:,:,3:4]/255.0
    pm=np.dstack([arr[:,:,:3]*a,arr[:,:,3:4]]).astype(np.uint8)
    q=np.array(Image.fromarray(pm,'RGBA').resize((wpx,hpx),Image.LANCZOS)).astype(np.float32); qa=q[:,:,3:4]/255.0
    rgb=np.where(qa>0.003,q[:,:,:3]/np.maximum(qa,0.003),0)
    return np.dstack([np.clip(rgb,0,255),q[:,:,3:4]]).astype(np.uint8)

SRC={'f3':(feet[2],False),'f4':(feet[3],False),'f5':(feet[4],True)}     # (component, flip so toes point left)
POSE_USE={0:'f3',3:'f4',4:'f5',5:'f3',6:'f3',7:'f4',8:'f5'}
cache={}
def process(key):
    if key in cache: return cache[key]
    comp,flip=SRC[key]
    crop=isolate(comp)
    if flip: crop=crop[:,::-1].copy()
    rgba=matte(to_rgba(crop),False)
    al=rgba[:,:,3]>128
    ys,xs=np.where(al); maxY=ys.max()
    h0=min(rgba.shape[0],maxY+2); top=max(0,h0-MAXH)
    rgba=rgba[top:h0]; al=rgba[:,:,3]>128
    ys,xs=np.where(al); maxY=ys.max(); h,w=rgba.shape[:2]
    foot=al[max(0,maxY-72):maxY+1]; fx=np.where(foot.any(axis=0))[0]
    soleMin=fx.min()/SXu; soleMax=(fx.max()+1)/SXu; botY=(maxY+1)/SYu; anchor=(soleMin+soleMax)/2
    soleYs=[]
    for t in range(24):
        xc=round((soleMin+(soleMax-soleMin)*t/23)*SXu); xc=min(w-1,max(0,xc)); yb=-1
        for y in range(h-1,-1,-1):
            if al[y,max(0,xc-1):min(w-1,xc+1)+1].any(): yb=y;break
        soleYs.append(round(((yb+1 if yb>=0 else maxY+1)/SYu)-botY,2))
    def centerAt(r):
        y=min(h-1,round(r*SYu)); xs_=np.where(al[y])[0]
        return None if len(xs_)==0 else (xs_[0]+xs_[-1]+1)/2/SXu
    c1,c2=centerAt(4),centerAt(30)
    slope=((c2-c1)/26) if (c1 is not None and c2 is not None) else 0
    wu=w/SXu; hu=h/SYu; wpx=max(2,round(wu*SX1*K)); hpx=min(256,max(2,round(hu*SY1*K)))
    fin=premul_resize(rgba,wpx,hpx)
    tex=np.zeros((256,256,4),np.uint8); tex[:hpx,:wpx]=fin
    info=dict(wu=wu,hu=hu,botY=botY,anchor=anchor,soleMin=soleMin,soleMax=soleMax,slope=slope,wpx=wpx,hpx=hpx,tw=256,th=256,soleYs=soleYs,tex=tex)
    cache[key]=info
    print(key,'src %dx%d'%(w,h),'units %.1f x %.1f'%(wu,hu),'px',wpx,hpx,'sole %.1f..%.1f'%(soleMin,soleMax),'slope %.3f'%slope)
    return info
poses=[]
for idx in range(11):
    info=process(POSE_USE.get(idx,'f3')); poses.append(info)
    if idx in POSE_USE: open(f'{OUT}/assets/strp_{idx:02d}.rgba','wb').write(swizzle(info['tex'],4))
with open(f'{OUT}/poses_c.h','w') as f:
    f.write('/* generated by tools/gen_char_c.py */\n#pragma once\nstatic const PoseInfo POSES_C[NPOSE] = {\n')
    for p in poses:
        f.write('  {%.3ff,%.3ff,%.3ff,%.3ff,%.3ff,%.3ff,%.4ff,%d,%d,%d,%d,{%s}},\n'%(p['wu'],p['hu'],p['botY'],p['anchor'],p['soleMin'],p['soleMax'],p['slope'],p['wpx'],p['hpx'],p['tw'],p['th'],','.join('%.2ff'%v for v in p['soleYs'])))
    f.write('};\n')
pw=[]
for i,c in enumerate(ports):
    crop=isolate(c,3)
    rgba=matte(to_rgba(crop),True); h_,w_=rgba.shape[:2]; th=64; tw=min(64,round(w_*th/h_))
    fin=premul_resize(rgba,tw,th); tex=np.zeros((64,64,4),np.uint8); tex[:th,:tw]=fin
    open(f'{OUT}/assets/sport_{i:02d}.rgba','wb').write(swizzle(tex,4)); pw.append(tw)
print('portrait widths',pw)
json.dump(pw,open(f'{OUT}/tools/portw_c.json','w'))
